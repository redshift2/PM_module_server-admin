-- OIDC provider configuration and verified external identity links.
-- Does not enable login. Back up H2 before deployment.
CREATE TABLE IF NOT EXISTS server_admin_oidc_provider (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    name VARCHAR(100) NOT NULL,
    issuer VARCHAR(500) NOT NULL,
    client_id VARCHAR(255) NOT NULL,
    encrypted_client_secret VARCHAR(2048),
    scopes VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    auto_create_users BOOLEAN NOT NULL DEFAULT FALSE,
    date_created TIMESTAMP,
    last_updated TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sa_oidc_provider_name ON server_admin_oidc_provider(name);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sa_oidc_provider_issuer ON server_admin_oidc_provider(issuer);
CREATE TABLE IF NOT EXISTS server_admin_oidc_identity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    user_id BIGINT NOT NULL,
    provider_id BIGINT NOT NULL,
    issuer VARCHAR(500) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    linked_at TIMESTAMP NOT NULL,
    last_login_at TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sa_oidc_issuer_sub ON server_admin_oidc_identity(issuer,subject);
CREATE INDEX IF NOT EXISTS ix_sa_oidc_identity_user ON server_admin_oidc_identity(user_id);
